-- Create active application entities mapped in the client but absent from both databases.
-- Additive only: no existing records are deleted or rewritten.

CREATE TABLE IF NOT EXISTS public.agency_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_profile_id bigint,
  requester_user_id bigint NOT NULL,
  requester_code text NOT NULL,
  requester_name text,
  requester_exchange_name text,
  requester_phone text,
  target_code text NOT NULL,
  target_name text,
  status text NOT NULL DEFAULT 'pending',
  city text,
  request_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.user_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_user_id text NOT NULL DEFAULT '',
  target_user_name text NOT NULL DEFAULT '',
  target_role text NOT NULL DEFAULT 'all',
  title text NOT NULL,
  message text NOT NULL,
  kind text NOT NULL DEFAULT 'custom',
  action_url text NOT NULL DEFAULT '',
  action_label text NOT NULL DEFAULT '',
  read boolean NOT NULL DEFAULT false,
  sent_by_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.payment_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text,
  user_name text,
  sarraaf_profile_id bigint,
  plan text,
  payment_status text,
  purchase_date timestamptz,
  start_date timestamptz,
  end_date timestamptz,
  is_active boolean NOT NULL DEFAULT true,
  confirmed_by_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.wallet_topup_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exchange_code text NOT NULL,
  user_id text NOT NULL,
  user_name text,
  created_by_id text,
  amount numeric(20,6) NOT NULL DEFAULT 0,
  currency text NOT NULL DEFAULT 'AFN',
  method text NOT NULL DEFAULT 'card_to_card',
  receipt_url text NOT NULL DEFAULT '',
  sender_name text NOT NULL DEFAULT '',
  card_last4 text NOT NULL DEFAULT '',
  transaction_time timestamptz,
  description text,
  status text NOT NULL DEFAULT 'pending',
  reviewer_id text,
  reviewer_name text,
  review_date timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.backup_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exchange_code text NOT NULL,
  user_id text NOT NULL DEFAULT '',
  user_name text NOT NULL DEFAULT '',
  type text NOT NULL DEFAULT 'manual',
  status text NOT NULL DEFAULT 'success',
  file_name text,
  size_bytes bigint NOT NULL DEFAULT 0,
  record_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  entity_types jsonb NOT NULL DEFAULT '[]'::jsonb,
  notes text,
  restore_date timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.recharge_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exchange_code text NOT NULL,
  operator_key text,
  operator_name text,
  operator_country text,
  phone_number text NOT NULL,
  package_type text NOT NULL DEFAULT 'credit',
  package_name text,
  amount numeric(20,6) NOT NULL DEFAULT 0,
  currency text NOT NULL DEFAULT 'AFN',
  status text NOT NULL DEFAULT 'pending',
  supplier_status text NOT NULL DEFAULT 'not_submitted',
  tracking_number text,
  receipt_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS agency_links_requester_idx ON public.agency_links(requester_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS agency_links_target_idx ON public.agency_links(target_code, status);
CREATE INDEX IF NOT EXISTS user_notifications_target_idx ON public.user_notifications(target_user_id, target_role, created_at DESC);
CREATE INDEX IF NOT EXISTS payment_records_user_idx ON public.payment_records(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS wallet_topup_requests_tenant_idx ON public.wallet_topup_requests(exchange_code, status, created_at DESC);
CREATE INDEX IF NOT EXISTS wallet_topup_requests_user_idx ON public.wallet_topup_requests(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS backup_records_owner_idx ON public.backup_records(exchange_code, user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS recharge_orders_tenant_idx ON public.recharge_orders(exchange_code, status, created_at DESC);

ALTER TABLE public.agency_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payment_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wallet_topup_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.backup_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recharge_orders ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.agency_links, public.user_notifications, public.payment_records,
  public.wallet_topup_requests, public.backup_records, public.recharge_orders TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.agency_links_id_seq, public.user_notifications_id_seq,
  public.payment_records_id_seq, public.wallet_topup_requests_id_seq, public.backup_records_id_seq,
  public.recharge_orders_id_seq TO anon, authenticated;

DROP POLICY IF EXISTS app_admin_all ON public.agency_links;
CREATE POLICY app_admin_all ON public.agency_links FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());
DROP POLICY IF EXISTS agency_links_requester_select ON public.agency_links;
CREATE POLICY agency_links_requester_select ON public.agency_links FOR SELECT USING (requester_user_id = public.app_uid());
DROP POLICY IF EXISTS agency_links_target_select ON public.agency_links;
CREATE POLICY agency_links_target_select ON public.agency_links FOR SELECT USING (target_code = public.app_ec());
DROP POLICY IF EXISTS agency_links_requester_insert ON public.agency_links;
CREATE POLICY agency_links_requester_insert ON public.agency_links FOR INSERT WITH CHECK (requester_user_id = public.app_uid() AND requester_code = public.app_ec());
DROP POLICY IF EXISTS agency_links_target_update ON public.agency_links;
CREATE POLICY agency_links_target_update ON public.agency_links FOR UPDATE USING (target_code = public.app_ec()) WITH CHECK (target_code = public.app_ec());

DROP POLICY IF EXISTS app_admin_all ON public.user_notifications;
CREATE POLICY app_admin_all ON public.user_notifications FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());
DROP POLICY IF EXISTS user_notifications_owner_select ON public.user_notifications;
CREATE POLICY user_notifications_owner_select ON public.user_notifications FOR SELECT
  USING (target_user_id = public.app_uid()::text OR target_role = 'all' OR target_role = (public.app_claims() ->> 'r'));
DROP POLICY IF EXISTS user_notifications_owner_update ON public.user_notifications;
CREATE POLICY user_notifications_owner_update ON public.user_notifications FOR UPDATE
  USING (target_user_id = public.app_uid()::text OR target_role = 'all' OR target_role = (public.app_claims() ->> 'r'))
  WITH CHECK (target_user_id = public.app_uid()::text OR target_role = 'all' OR target_role = (public.app_claims() ->> 'r'));

DROP POLICY IF EXISTS app_admin_all ON public.payment_records;
CREATE POLICY app_admin_all ON public.payment_records FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());

DROP POLICY IF EXISTS app_admin_all ON public.wallet_topup_requests;
CREATE POLICY app_admin_all ON public.wallet_topup_requests FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());
DROP POLICY IF EXISTS wallet_topup_owner_insert ON public.wallet_topup_requests;
CREATE POLICY wallet_topup_owner_insert ON public.wallet_topup_requests FOR INSERT
  WITH CHECK (user_id = public.app_uid()::text AND exchange_code = public.app_ec());
DROP POLICY IF EXISTS wallet_topup_owner_select ON public.wallet_topup_requests;
CREATE POLICY wallet_topup_owner_select ON public.wallet_topup_requests FOR SELECT
  USING (user_id = public.app_uid()::text);

DROP POLICY IF EXISTS app_admin_all ON public.backup_records;
CREATE POLICY app_admin_all ON public.backup_records FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());
DROP POLICY IF EXISTS backup_records_owner_all ON public.backup_records;
CREATE POLICY backup_records_owner_all ON public.backup_records FOR ALL
  USING (user_id = public.app_uid()::text AND exchange_code = public.app_ec())
  WITH CHECK (user_id = public.app_uid()::text AND exchange_code = public.app_ec());

DROP POLICY IF EXISTS app_admin_all ON public.recharge_orders;
CREATE POLICY app_admin_all ON public.recharge_orders FOR ALL USING (public.app_is_admin()) WITH CHECK (public.app_is_admin());
DROP POLICY IF EXISTS recharge_orders_sarraaf_all ON public.recharge_orders;
CREATE POLICY recharge_orders_sarraaf_all ON public.recharge_orders FOR ALL
  USING (exchange_code = public.app_ec() AND (public.app_claims() ->> 'r') = 'sarraaf')
  WITH CHECK (exchange_code = public.app_ec() AND (public.app_claims() ->> 'r') = 'sarraaf');

DO $triggers$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['agency_links','user_notifications','payment_records','wallet_topup_requests','backup_records','recharge_orders']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', 'trg_' || t || '_updated_at', t);
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.update_updated_at()', 'trg_' || t || '_updated_at', t);
  END LOOP;
END
$triggers$;
